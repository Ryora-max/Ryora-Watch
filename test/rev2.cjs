const puppeteer = require('puppeteer');
const B = 'http://localhost:3000';
const post = (p, b, t) => fetch(B + p, { method: 'POST', headers: { 'Content-Type': 'application/json', ...(t ? { 'x-token': t } : {}) }, body: JSON.stringify(b || {}) }).then(r => r.json());
(async () => {
  const ua = await post('/api/register', { name: 'Sky' });
  const ub = await post('/api/register', { name: 'Tiara' });
  const pc = await post('/api/pair/create', {}, ua.token);
  await post('/api/pair/join', { code: pc.code }, ub.token);
  await post('/api/expense', { kind: 'in', amount: 500000, note: 'uang saku', pot: 'daily' }, ua.token);
  await post('/api/expense', { kind: 'out', amount: 75000, note: 'makan siang', pot: 'daily' }, ub.token);
  await post('/api/expense', { kind: 'in', amount: 150000, pot: 'saving' }, ua.token);
  await post('/api/expense', { kind: 'in', amount: 100000, pot: 'saving' }, ub.token);
  await post('/api/goal', { name: 'date ke bandung', amount: 1000000 }, ua.token);
  const browser = await puppeteer.launch({ headless: 'new', });
  const page = await browser.newPage();
  await page.setViewport({ width: 390, height: 844, isMobile: true });
  page.on('pageerror', e => console.log('ERR', e.message.slice(0, 100)));
  await page.evaluateOnNewDocument(t => { localStorage.cw_setup_done = '1'; localStorage.cw_token = t; localStorage.cw_toured = '1'; }, ua.token);
  await page.goto(B, { waitUntil: 'domcontentloaded' });
  await new Promise(r => setTimeout(r, 4000));
  await page.evaluate(() => document.querySelector('[data-t="uang"]').click());
  await new Promise(r => setTimeout(r, 1500));
  await page.screenshot({ path: 'test/rev_uang2.png' });
  await page.evaluate(() => document.querySelector('[data-t="miss"]').click());
  await new Promise(r => setTimeout(r, 1000));
  await page.evaluate(() => document.querySelector('#ultaBtn').click());
  await new Promise(r => setTimeout(r, 800));
  await page.evaluate(() => document.querySelector('#ulRoll').click());
  await new Promise(r => setTimeout(r, 800));
  await page.screenshot({ path: 'test/rev_ulta.png' });
  await browser.close();
  console.log('done');
})().catch(e => { console.log('FATAL', e.message); process.exit(1); });
