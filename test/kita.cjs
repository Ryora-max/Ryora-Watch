const puppeteer = require('puppeteer');
const B = 'http://localhost:3000';
const post = (p, b, t) => fetch(B + p, { method: 'POST', headers: { 'Content-Type': 'application/json', ...(t ? { 'x-token': t } : {}) }, body: JSON.stringify(b || {}) }).then(r => r.json());
(async () => {
  const ua = await post('/api/register', { name: 'Sky' });
  const ub = await post('/api/register', { name: 'Tiara' });
  const pc = await post('/api/pair/create', {}, ua.token);
  await post('/api/pair/join', { code: pc.code }, ub.token);
  await post('/api/expense', { kind: 'out', amount: 45000, note: 'makan bareng' }, ua.token);
  await post('/api/expense', { kind: 'in', amount: 200000, note: 'nabung bulanan' }, ub.token);
  await post('/api/habit', { name: 'minum air' }, ua.token);
  const browser = await puppeteer.launch({ headless: 'new', userDataDir: require('os').tmpdir() + '/pk_' + Date.now() });
  const page = await browser.newPage();
  await page.setViewport({ width: 390, height: 844, isMobile: true });
  page.on('pageerror', e => console.log('ERR', e.message));
  await page.evaluateOnNewDocument(t => { localStorage.cw_setup_done = '1'; localStorage.cw_token = t; localStorage.cw_toured = '1'; }, ua.token);
  await page.goto(B, { waitUntil: 'domcontentloaded' });
  await new Promise(r => setTimeout(r, 3000));
  await page.evaluate(() => document.querySelector('[data-t="kita"]')?.click());
  await new Promise(r => setTimeout(r, 2000));
  await page.evaluate(() => document.querySelector('#expSum')?.scrollIntoView({ block: 'center' }));
  await new Promise(r => setTimeout(r, 400));
  await page.screenshot({ path: 'test/shot_kita2.png' });
  await page.evaluate(() => document.querySelector('[data-t="miss"]')?.click());
  await new Promise(r => setTimeout(r, 1800));
  await page.evaluate(() => document.querySelector('#league')?.scrollIntoView({ block: 'center' }));
  await new Promise(r => setTimeout(r, 400));
  await page.screenshot({ path: 'test/shot_main.png' });
  await page.evaluate(() => document.querySelector('[data-t="sched"]')?.click());
  await new Promise(r => setTimeout(r, 1500));
  await page.evaluate(() => document.querySelector('#habitList')?.scrollIntoView({ block: 'center' }));
  await page.screenshot({ path: 'test/shot_sched3.png' });
  await browser.close();
  console.log('done');
})();
